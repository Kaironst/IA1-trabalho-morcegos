# script do chatgpt

input_file = "Names.txt"
output_file = "NamesWithClass.txt"

with open(input_file, "r", encoding="utf-8") as infile, \
        open(output_file, "w", encoding="utf-8", newline="") as outfile:

    for line in infile:
        # Preserve the original line ending separately.
        newline = "\r\n" if line.endswith("\r\n") else \
                  "\n" if line.endswith("\n") else \
                  "\r" if line.endswith("\r") else ""

        record = line[:-len(newline)] if newline else line

        # Extract genus from the species name.
        species_name = record.strip()
        genus = species_name.split("_")[0] if species_name else ""

        # Assign label.
        label = "1" if genus in bat_genera else "0"

        # Ensure the line has at least 82 characters.
        record = record.ljust(82)

        # Write the label at index 81.
        record = record[:81] + label + record[82:]

        outfile.write(record + newline)

print(f"Labeled file saved to {output_file}")
